#!/usr/bin/env node
// ─────────────────────────────────────────────────────────────────────────
// Regenerates test-src/AppUnderTest.jsx from src/App.jsx.
//
// Why this exists: AppUnderTest.jsx is a copy of the real app source plus
// one trailing `export { ... }` block that exposes internal components
// (DiagramCenter, SyllabusView, sb, etc.) for the test suite, since
// src/App.jsx itself only default-exports <App/>. Before this script,
// that copy was made by hand and drifted from src/App.jsx — the test
// suite quietly kept testing old code. This script is the single source
// of truth for the copy: it always regenerates AppUnderTest.jsx from the
// CURRENT src/App.jsx, so "npm test" can never run against stale source.
//
// Usage: node scripts/sync-app-under-test.mjs
// Runs automatically via the "pretest"/"pretest:watch" npm hooks — see
// package.json. Exits non-zero with a clear message on any failure
// (missing source, unwritable destination, etc.) so a broken sync can
// never be silently skipped.
// ─────────────────────────────────────────────────────────────────────────
import { existsSync, readFileSync, writeFileSync, mkdirSync } from "fs";
import { dirname, resolve } from "path";
import { fileURLToPath } from "url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, "..");
const SRC_PATH = resolve(ROOT, "src/App.jsx");
const DEST_PATH = resolve(ROOT, "test-src/AppUnderTest.jsx");

// This is the ONE canonical list of test-only exports. Add a new name here
// (and only here) when a new component/helper needs to be reachable from a
// test file — the trailer is generated fresh every sync, so there is no
// second copy of this list to fall out of sync.
const TEST_ONLY_EXPORTS = [
  "DiagramGame", "DiagramCenter", "DIAGRAM_DATA", "normalizeDiagram", "DIAGRAM_SVG_COMPONENTS",
  "sb", "ConnectedNotesTab", "NotesView", "PdfPageRenderer", "ConnectedQuestionsTab",
  "ConnectedTestsTab", "QuestionsView", "QuizPlayer", "useAnswerReveal", "ANSWER_LOCKED_MSG",
  "SyllabusView", "ChapterPage", "AITutor", "StudyPlanner", "ProfileView", "useIsNarrow",
  "useUiMode", "UI_MODES", "UI_MODE_STORAGE_KEY",
  "BioVisionShell", "CurrentShell", "ActivePage", "BioVisionNav", "BIOVISION_NAV_ITEMS", "GlobalAppStyles",
  "BioVisionHome", "Dashboard", "useDashboardData", "callBioAI",
];

const TRAILER = `

// ── TEST-ONLY EXPORTS ──────────────────────────────────────────────
// This file is a throwaway copy, regenerated automatically by
// scripts/sync-app-under-test.mjs (see "pretest" in package.json) from
// src/App.jsx on every test run. Do not edit this file by hand — your
// edits will be overwritten on the next "npm test". The real deliverable
// at src/App.jsx / outputs/App.jsx is NOT modified — this block does not
// exist there.
export { ${TEST_ONLY_EXPORTS.join(", ")} };
`;

function fail(message) {
  console.error(`\n✗ AppUnderTest sync failed: ${message}\n`);
  process.exit(1);
}

if (!existsSync(SRC_PATH)) {
  fail(`source file not found at ${SRC_PATH}. Cannot regenerate the test mirror without it.`);
}

let source;
try {
  source = readFileSync(SRC_PATH, "utf8");
} catch (e) {
  fail(`could not read ${SRC_PATH}: ${e.message}`);
}

if (!source || source.trim().length === 0) {
  fail(`${SRC_PATH} is empty — refusing to regenerate the test mirror from empty source.`);
}

try {
  mkdirSync(dirname(DEST_PATH), { recursive: true });
  writeFileSync(DEST_PATH, source + TRAILER, "utf8");
} catch (e) {
  fail(`could not write ${DEST_PATH}: ${e.message}`);
}

// Prove the write actually landed and matches what we intended, rather
// than trusting a silent success from writeFileSync.
let verify;
try {
  verify = readFileSync(DEST_PATH, "utf8");
} catch (e) {
  fail(`wrote ${DEST_PATH} but could not read it back to verify: ${e.message}`);
}
if (verify !== source + TRAILER) {
  fail(`${DEST_PATH} does not match the intended content after writing — sync did not land cleanly.`);
}

console.log(`✓ AppUnderTest synced from src/App.jsx (${source.length} bytes + test-only export trailer)`);
